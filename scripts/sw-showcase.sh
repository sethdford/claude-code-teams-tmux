#!/usr/bin/env bash
# ╔═══════════════════════════════════════════════════════════════════════════╗
# ║  sw-showcase.sh — Tech Stack Example Repository Generator                ║
# ║                                                                          ║
# ║  Scaffolds a minimal example repository demonstrating Shipwright         ║
# ║  adoption for a target tech stack (node, python, go).                    ║
# ╚═══════════════════════════════════════════════════════════════════════════╝
# shellcheck disable=SC2034
VERSION="3.3.0"
set -euo pipefail
trap 'echo "ERROR: $BASH_SOURCE:$LINENO exited with status $?" >&2' ERR

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# shellcheck source=lib/helpers.sh
[[ -f "$SCRIPT_DIR/lib/helpers.sh" ]] && source "$SCRIPT_DIR/lib/helpers.sh"
[[ "$(type -t info 2>/dev/null)" == "function" ]]    || info()    { echo -e "\033[38;2;0;212;255m\033[1m▸\033[0m $*"; }
[[ "$(type -t success 2>/dev/null)" == "function" ]] || success() { echo -e "\033[38;2;74;222;128m\033[1m✓\033[0m $*"; }
[[ "$(type -t warn 2>/dev/null)" == "function" ]]    || warn()    { echo -e "\033[38;2;250;204;21m\033[1m⚠\033[0m $*"; }
[[ "$(type -t error 2>/dev/null)" == "function" ]]   || error()   { echo -e "\033[38;2;248;113;113m\033[1m✗\033[0m $*" >&2; }
[[ "$(type -t emit_event 2>/dev/null)" == "function" ]] || emit_event() { :; }

show_help() {
    cat <<EOF
USAGE
  shipwright showcase --stack <node|python|go> --out <dir> [--force]

DESCRIPTION
  Generate a minimal example repository scaffolded with Shipwright integration
  for the target tech stack. Useful for demos, onboarding, and adoption.

OPTIONS
  --stack <name>   Target stack: node, python, or go (required)
  --out <dir>      Output directory (required)
  --force          Overwrite existing non-empty output directory
  --help, -h       Show this help text
  --version, -v    Show version

EXAMPLES
  shipwright showcase --stack node --out /tmp/sw-demo-node
  shipwright showcase --stack python --out ./demo --force
  shipwright showcase --stack go --out ~/showcase

OUTPUT
  Creates README.md, source/test files for the stack, and a .claude/ directory
  with CLAUDE.md and daemon-config.json for Shipwright integration.
EOF
}

# Atomic write: write to tmp then mv
atomic_write() {
    local path="$1" content="$2"
    local dir tmp
    dir="$(dirname "$path")"
    mkdir -p "$dir"
    tmp="$(mktemp "${dir}/.sw-showcase.XXXXXX")"
    printf '%s' "$content" > "$tmp"
    mv "$tmp" "$path"
}

write_common() {
    local out="$1" stack="$2"
    atomic_write "$out/README.md" "# Shipwright ${stack} Showcase

A minimal ${stack} project demonstrating Shipwright autonomous agent integration.

## Quick Start

This scaffold shows how to wire Shipwright into a ${stack} project. See
\`.claude/CLAUDE.md\` for project-specific agent instructions and
\`.claude/daemon-config.json\` for daemon configuration.

## Files

- \`.claude/CLAUDE.md\` — Project conventions for AI agents
- \`.claude/daemon-config.json\` — Shipwright daemon configuration

Generated by \`shipwright showcase --stack ${stack}\`.
"

    atomic_write "$out/.gitignore" "# Shipwright artifacts
.claude/pipeline-artifacts/
.claude/intelligence-cache.json
.claude/loop-state.md

# Common
node_modules/
__pycache__/
*.pyc
.venv/
dist/
build/
.DS_Store
"

    atomic_write "$out/.claude/CLAUDE.md" "# Project Instructions

This is a Shipwright showcase for the **${stack}** stack.

## Conventions

- Keep changes minimal and focused
- All new functions must have tests
- Run the full test suite before committing
"

    # Build daemon-config.json with jq for proper escaping
    local cfg
    cfg=$(jq -n --arg stack "$stack" '{
        stack: $stack,
        max_parallel: 2,
        auto_scale: false,
        auto_template: true,
        max_retries: 2,
        intelligence: { enabled: true }
    }')
    atomic_write "$out/.claude/daemon-config.json" "$cfg"
}

write_node() {
    local out="$1"
    local pkg
    pkg=$(jq -n '{
        name: "shipwright-showcase-node",
        version: "0.1.0",
        description: "Shipwright Node.js showcase",
        main: "src/index.js",
        scripts: { test: "node --test test/" },
        license: "MIT"
    }')
    atomic_write "$out/package.json" "$pkg"
    atomic_write "$out/src/index.js" "// Shipwright Node.js showcase entry point
function greet(name) {
    return \`Hello, \${name}!\`;
}

module.exports = { greet };
"
    atomic_write "$out/test/index.test.js" "const test = require('node:test');
const assert = require('node:assert');
const { greet } = require('../src/index.js');

test('greet returns greeting', () => {
    assert.strictEqual(greet('world'), 'Hello, world!');
});
"
}

write_python() {
    local out="$1"
    atomic_write "$out/pyproject.toml" "[project]
name = \"shipwright-showcase-python\"
version = \"0.1.0\"
description = \"Shipwright Python showcase\"
requires-python = \">=3.9\"

[build-system]
requires = [\"setuptools>=61\"]
build-backend = \"setuptools.build_meta\"
"
    atomic_write "$out/src/showcase/__init__.py" "def greet(name: str) -> str:
    return f\"Hello, {name}!\"
"
    atomic_write "$out/tests/test_showcase.py" "from src.showcase import greet


def test_greet():
    assert greet(\"world\") == \"Hello, world!\"
"
}

write_go() {
    local out="$1"
    atomic_write "$out/go.mod" "module github.com/example/shipwright-showcase-go

go 1.21
"
    atomic_write "$out/main.go" "package main

import \"fmt\"

func Greet(name string) string {
    return fmt.Sprintf(\"Hello, %s!\", name)
}

func main() {
    fmt.Println(Greet(\"world\"))
}
"
    atomic_write "$out/main_test.go" "package main

import \"testing\"

func TestGreet(t *testing.T) {
    got := Greet(\"world\")
    want := \"Hello, world!\"
    if got != want {
        t.Errorf(\"Greet() = %q, want %q\", got, want)
    }
}
"
}

main() {
    local stack="" out="" force="false"

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --help|-h)
                show_help
                exit 0
                ;;
            --version|-v)
                echo "$VERSION"
                exit 0
                ;;
            --stack)
                stack="${2:-}"
                shift 2 || { error "--stack requires a value"; exit 1; }
                ;;
            --out)
                out="${2:-}"
                shift 2 || { error "--out requires a value"; exit 1; }
                ;;
            --force)
                force="true"
                shift
                ;;
            *)
                error "Unknown option: $1"
                show_help
                exit 1
                ;;
        esac
    done

    if [[ -z "$stack" ]]; then
        error "--stack is required (node|python|go)"
        exit 1
    fi
    if [[ -z "$out" ]]; then
        error "--out is required"
        exit 1
    fi
    case "$stack" in
        node|python|go) ;;
        *)
            error "Unsupported stack: $stack (must be node, python, or go)"
            exit 1
            ;;
    esac

    if [[ -d "$out" ]] && [[ -n "$(ls -A "$out" 2>/dev/null)" ]] && [[ "$force" != "true" ]]; then
        error "Output directory exists and is not empty: $out (use --force to overwrite)"
        exit 1
    fi

    if ! command -v jq >/dev/null 2>&1; then
        error "jq is required but not installed"
        exit 1
    fi

    mkdir -p "$out"
    info "Generating $stack showcase at $out"

    write_common "$out" "$stack"
    case "$stack" in
        node)   write_node "$out" ;;
        python) write_python "$out" ;;
        go)     write_go "$out" ;;
    esac

    emit_event "showcase.generated" "stack=$stack" "out=$out"
    success "Showcase generated: $out"
    info "  Stack:  $stack"
    info "  Files:  $(find "$out" -type f | wc -l | tr -d ' ')"
}

main "$@"
